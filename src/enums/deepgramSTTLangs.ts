export const getDeepgramSTTLanguageInfo = (code: DeepgramSTTLanguageCode | string) => {
  const metadata = DEEPGRAM_STT_LANGUAGE_METADATA[code as DeepgramSTTLanguageCode]
  return {
    code,
    name: metadata?.name || 'Unknown',
    nativeName: metadata?.nativeName,
    flag: metadata?.flag || '🏳️',
    region: metadata?.region || 'Unknown',
  }
}

export const getAllDeepgramSTTLanguages = () =>
  Object.values(DeepgramSTTLanguageCode).map((code) => getDeepgramSTTLanguageInfo(code))

export const isValidDeepgramSTTLanguageCode = (code: string): code is DeepgramSTTLanguageCode =>
  Object.values(DeepgramSTTLanguageCode).includes(code as DeepgramSTTLanguageCode)

